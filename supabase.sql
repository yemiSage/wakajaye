BEGIN;
CREATE SCHEMA IF NOT EXISTS wakajaye;
REVOKE ALL ON SCHEMA wakajaye FROM PUBLIC, anon, authenticated;

CREATE TABLE IF NOT EXISTS wakajaye.tenants (
  email text PRIMARY KEY, profile text, guarantor text, rent text
);
CREATE TABLE IF NOT EXISTS wakajaye.codes (
  email text PRIMARY KEY, digest text NOT NULL, issued double precision NOT NULL,
  attempts integer NOT NULL, mode text NOT NULL
);
CREATE TABLE IF NOT EXISTS wakajaye.sessions (
  token text PRIMARY KEY, email text NOT NULL REFERENCES wakajaye.tenants(email),
  expires double precision NOT NULL
);
CREATE TABLE IF NOT EXISTS wakajaye.receipts (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  email text NOT NULL UNIQUE REFERENCES wakajaye.tenants(email),
  name text NOT NULL, mime text NOT NULL, bytes bytea NOT NULL,
  status text NOT NULL CHECK (status IN ('pending', 'verified'))
);
REVOKE ALL ON ALL TABLES IN SCHEMA wakajaye FROM PUBLIC, anon, authenticated;
ALTER TABLE wakajaye.tenants ENABLE ROW LEVEL SECURITY;
ALTER TABLE wakajaye.codes ENABLE ROW LEVEL SECURITY;
ALTER TABLE wakajaye.sessions ENABLE ROW LEVEL SECURITY;
ALTER TABLE wakajaye.receipts ENABLE ROW LEVEL SECURITY;
COMMIT;
